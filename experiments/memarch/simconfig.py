"""r2-sim configurations of the memarch experiment: one SM under a root.

The address layout and the PE list are fixed (one kernel build serves every
point); a design point changes only rates and sizes that do not move an
address. `write(point, dir)` writes `device.yaml` and `sm.yaml` there.

Layout of the SM (offsets in its own space):
  smem  0x0000000 .. 0x0100000   (1 MiB range; the design's capacity is checked
                                  analytically, the range is only an address space)
  tmem  0x1000000 .. 0x1100000   (1 MiB range, same)
  hbm   0x10000000 .. 0x50000000 (ideal: no latency, 1 MiB/cycle)

Buses: lbus holds smem, hbm, Atlas, DMA; tbus holds tmem (Atlas and DMA
master it too). Each Muon core w masters two buses of its own: ms<w>, linked
to lbus (its crossbar port into smem: lanes x 4 B x pattern efficiency), and
mt<w>, linked to tbus (its fixed lane partition of tmem).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

DEVICE = """\
# memarch experiment: a root with one SM (generated by experiments/memarch/simconfig.py).
global:
  neutrino_granule: 512
  clock_ghz: 1.0
  msg_bytes: 64
  flow: readyvalid
  hop_queue: 1
  address:
    fields: [{{name: sm, bits: 1}}]
    offset_bits: 33
device:
  name: root
  fabric:
    - {{name: sbus, topology: xbar}}
    - {{name: cbus, topology: xbar, bw_bytes: 8, beat_bytes: 8, control: true}}
  memory:
    - {{name: sync, type: sync, addr: [[0x1F0000000, 0x1F1000000]]}}
  neutrino: {nu}
  children:
    - {{name: sm0, config: sm.yaml}}
"""

NEUTRINO = ("{scoreboard: 1024, pending: 1024, execution: 1024, versions: 4096, "
            "inbound_refs: 1024, inbound_invokes: 256, outbound_deps: 1024, outbound_invokes: 256}")


@dataclass
class SimPoint:
    """The rates of one design point (bytes per cycle unless noted)."""

    # Atlas: MACs per cycle (bf16; fp8 the same MAC rate) and its smem read
    # port (None: no limit but the memory ports).
    macs: int = 1024
    atlas_port: int | None = None
    acc_buffer: int = 8192          # in-array accumulator (2 x 32x32 fp32)
    # smem: aggregate read and write (1R1W macros: separate channels).
    smem_rd: int = 256
    smem_wr: int = 256
    # tmem: aggregate read and write; 0 = no tmem (a token rate, unused).
    tmem_rd: int = 0
    tmem_wr: int = 0
    # Muon: cores, lane-ops per cycle per core, crossbar port per core into
    # smem (already scaled by the access pattern's efficiency), tmem
    # partition port per core.
    muons: int = 2
    muon_ops: int = 128
    muon_smem: dict = field(default_factory=lambda: {0: 64, 1: 64})
    muon_tmem: dict = field(default_factory=lambda: {0: 64, 1: 64})
    muon_overhead: int = 50
    # DMA: in flight and beat (wide: the memory write port limits it).
    dma_inflight: int = 8
    dma_beat: int = 4096


def _rate(x: float) -> str:
    """A rate for the YAML: an integer, or a decimal (the loader reads both)."""
    x = max(float(x), 1e-3)
    return str(int(x)) if x == int(x) else f"{x:.4f}"


def sm_yaml(p: SimPoint) -> str:
    tmem_rd = p.tmem_rd or 1
    tmem_wr = p.tmem_wr or 1
    lines = [
        "# One SM of the memarch experiment (generated).",
        "fabric:",
        "  - {name: smsbus, topology: xbar}",
        "  - {name: smcbus, topology: xbar, bw_bytes: 8, beat_bytes: 8, control: true}",
        "  - {name: lbus, topology: xbar}",
        "  - {name: tbus, topology: xbar}",
        "  - {name: smsbus_to_sbus, topology: link, from: $this.smsbus, to: $parent.sbus, bw_bytes: 128, wr_bytes: 128, latency: 10}",
        "  - {name: smcbus_to_cbus, topology: link, from: $this.smcbus, to: $parent.cbus, bw_bytes: 8, beat_bytes: 8, latency: 10, control: true}",
    ]
    for w in range(p.muons):
        s, t = _rate(p.muon_smem[w]), _rate(p.muon_tmem[w])
        lines += [
            f"  - {{name: ms{w}, topology: xbar}}",
            f"  - {{name: mt{w}, topology: xbar}}",
            f"  - {{name: m{w}_smem, topology: link, from: $this.ms{w}, to: $this.lbus, bw_bytes: {s}, beat_bytes: 4}}",
            f"  - {{name: m{w}_tmem, topology: link, from: $this.mt{w}, to: $this.tbus, bw_bytes: {t}, beat_bytes: 4}}",
        ]
    lines += [
        "memory:",
        f"  - {{name: smem, type: scratch, addr: [[0x0, 0x100000]], bw_bytes: {_rate(p.smem_rd)}, wr_bytes: {_rate(p.smem_wr)}, beat_bytes: 4, latency: 2, slave: [$this.lbus, $this.smsbus]}}",
        f"  - {{name: tmem, type: tmem, rules: free, addr: [[0x1000000, 0x1100000]], bw_bytes: {_rate(tmem_rd)}, wr_bytes: {_rate(tmem_wr)}, beat_bytes: 4, latency: 2, slave: [$this.tbus]}}",
        "  - {name: hbm, type: dram, addr: [[0x10000000, 0x50000000]], bw_bytes: 1048576, latency: 0, slave: $this.lbus}",
        "  - {name: sync, type: sync, addr: [[0x1F0000000, 0x1F1000000]]}",
        "compute:",
    ]
    port = f", port_bytes: {_rate(p.atlas_port)}" if p.atlas_port else ""
    lines.append(
        f"  - {{name: atlas, type: tensor, rate: {{bf16: {p.macs}, fp8: {p.macs}}}, tile: [128, 128], "
        f"quantize: none, operand_reuse: none, acc_buffer: {p.acc_buffer}, beat_bytes: 4096{port}, inflight: 2, "
        "master: [$this.lbus, $this.tbus]}"
    )
    for w in range(p.muons):
        lines.append(
            f"  - {{name: muon{w}, type: vector, rate: {{lane_op: {p.muon_ops}}}, overhead: {p.muon_overhead}, "
            f"beat_bytes: 4, master: [$this.ms{w}, $this.mt{w}]}}"
        )
    lines += [
        f"  - {{name: dma, type: dma, latency: 0, inflight: {p.dma_inflight}, beat_bytes: {p.dma_beat}, master: [$this.lbus, $this.tbus]}}",
        f"neutrino: {NEUTRINO[:-1]}, c_invoke: 8, master: [$this.smcbus, $this.lbus, $this.smsbus]}}",
    ]
    return "\n".join(lines) + "\n"


def write(p: SimPoint, out: Path) -> Path:
    """Writes device.yaml and sm.yaml into `out`; the device config's path."""
    out.mkdir(parents=True, exist_ok=True)
    (out / "device.yaml").write_text(DEVICE.format(nu=NEUTRINO))
    (out / "sm.yaml").write_text(sm_yaml(p))
    return out / "device.yaml"


if __name__ == "__main__":
    import sys

    print(write(SimPoint(tmem_rd=256, tmem_wr=256), Path(sys.argv[1] if len(sys.argv) > 1 else "configs/base")))
